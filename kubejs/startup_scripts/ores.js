// Reuse TFC's rock enum so fantasy ores need one block ID per quality.
const FantasyOreEnumProperty = Java.loadClass('net.minecraft.world.level.block.state.properties.EnumProperty')
const FantasyOreRockEnum = Java.loadClass('net.dries007.tfc.common.blocks.rock.Rock')
const FantasyOreRockValues = new (Java.loadClass('java.util.ArrayList'))()
FantasyOreRockEnum.values().forEach(rock => FantasyOreRockValues.add(rock))
// Select the Collection overload explicitly; Rhino also accepts lists as varargs.
const FantasyOreRockProperty = FantasyOreEnumProperty['create(java.lang.String,java.lang.Class,java.util.Collection)'](
    'rock', 'net.dries007.tfc.common.blocks.rock.Rock', FantasyOreRockValues
)
if (FantasyOreRockProperty.getPossibleValues().size() !== FantasyOreRockValues.size()) {
    throw new Error('Fantasy ore rock property did not include all TFC rocks')
}

